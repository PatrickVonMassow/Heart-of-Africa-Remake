// Builder for scripts/fixtures/timestamp-guard-302ms-race.json — the replay of
// the measured 302 ms Stop-hook race (point 769).
//
// WHY A BUILDER AND NOT JUST THE JSON. The fixture's whole claim is that it is
// REAL: verbatim transcript rows, and an elided middle that changes nothing.
// A fixture asserting that about itself proves nothing, so the derivation lives
// here instead. On the batch machine the source transcript is present and the
// unit case rebuilds the fixture from it and demands equality — which measures
// the elided rows for real. Off that machine the transcript is absent (it is a
// private session log and cannot be committed) and the case skips, exactly as
// the document-cut accounting does for the user-level files it reads.
//
// Regenerate: node scripts/timestamp-race-fixture.mjs [--transcript <path>]
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { resolve } from 'node:path'

/** The session whose race this fixture replays, and the rows that carry it. */
export const RACE_SESSION = 'd5fcb9cf-2936-4743-9502-f504f08b8ac5'
export const NARRATION_ROW = 711
export const LAST_TOOL_RESULT_ROW = 948
export const FINAL_REPLY_ROW = 950
export const STOP_FEEDBACK_ROW = 953
export const TAIL_FROM = 930
export const TAIL_TO = 949
/** Long bodies are cut so the fixture stays reviewable; the served refusal is not. */
export const CAP = 120
export const REFUSAL_CAP = 4000

export function raceTranscriptPath(home = homedir()) {
  return resolve(home, '.claude', 'projects', '-workspace-hoa', `${RACE_SESSION}.jsonl`)
}

/** Truncate every string body past `cap`, leaving structure and non-strings alone. */
function truncate(value, cap) {
  if (typeof value === 'string') return value.length > cap ? `${value.slice(0, cap)}…` : value
  if (Array.isArray(value)) return value.map((v) => truncate(v, cap))
  if (value && typeof value === 'object') {
    const out = {}
    for (const key of Object.keys(value)) out[key] = truncate(value[key], cap)
    return out
  }
  return value
}

/** Build the fixture from the raw transcript text. Pure — no filesystem. */
export function buildRaceFixture(jsonl) {
  const lines = jsonl.split('\n')
  const row = (n, cap = CAP) => truncate(JSON.parse(lines[n - 1]), cap)

  const tail = []
  for (let n = TAIL_FROM; n <= TAIL_TO; n++) tail.push(row(n))

  // The elided middle is MEASURED here, at derivation time, from the real rows.
  let assistantTextRows = 0
  let sidechainTextRows = 0
  for (let n = NARRATION_ROW + 1; n < TAIL_FROM; n++) {
    let entry
    try {
      entry = JSON.parse(lines[n - 1])
    } catch {
      continue
    }
    const content = entry.message && entry.message.content
    if (entry.type !== 'assistant' || !Array.isArray(content)) continue
    if (!content.find((b) => b && b.type === 'text' && String(b.text).trim() !== '')) continue
    if (entry.isSidechain) sidechainTextRows += 1
    else assistantTextRows += 1
  }

  const narration = JSON.parse(lines[NARRATION_ROW - 1])
  return {
    '//': [
      'REAL slice of the measured 302 ms Stop-hook race (session d5fcb9cf, 20.08.2026).',
      'Generated by scripts/timestamp-race-fixture.mjs — never edited by hand. Every row is',
      'a verbatim transcript row with its own message.id, uuid, parentUuid, isSidechain flag,',
      `timestamp and shape kept; only string bodies over ${CAP} characters are cut with a`,
      'trailing …, and the served refusal in stopFeedbackRow is kept whole as the evidence.',
      'The rows between the narration and the tail are elided, and what they hold is MEASURED',
      'in source.elidedRows rather than assumed. The unit case rebuilds this file from the',
      'transcript wherever it is present, so the measurement is re-taken, not re-asserted.',
    ],
    source: {
      transcript: `~/.claude/projects/-workspace-hoa/${RACE_SESSION}.jsonl`,
      totalRows: lines.filter((l) => l.trim()).length,
      narrationRow: NARRATION_ROW,
      lastToolResultRow: LAST_TOOL_RESULT_ROW,
      finalReplyRow: FINAL_REPLY_ROW,
      stopFeedbackRow: STOP_FEEDBACK_ROW,
      tailRows: `${TAIL_FROM}-${TAIL_TO}`,
      elidedRows: {
        from: NARRATION_ROW + 1,
        to: TAIL_FROM - 1,
        count: TAIL_FROM - NARRATION_ROW - 1,
        assistantTextRows,
        sidechainTextRows,
      },
      truncatedStringsLongerThan: CAP,
    },
    sessionId: RACE_SESSION,
    narrationText: narration.message.content.find((b) => b.type === 'text').text,
    rowsBeforeFinalReply: [row(NARRATION_ROW), ...tail],
    finalReplyRow: row(FINAL_REPLY_ROW),
    stopFeedbackRow: row(STOP_FEEDBACK_ROW, REFUSAL_CAP),
  }
}

export const FIXTURE_PATH = resolve(
  process.cwd(),
  'scripts',
  'fixtures',
  'timestamp-guard-302ms-race.json',
)

if (process.argv[1] && process.argv[1].endsWith('timestamp-race-fixture.mjs')) {
  const flag = process.argv.indexOf('--transcript')
  const path = flag === -1 ? raceTranscriptPath() : process.argv[flag + 1]
  if (!existsSync(path)) {
    console.error(`timestamp-race-fixture: transcript not found: ${path}`)
    process.exit(1)
  }
  writeFileSync(FIXTURE_PATH, `${JSON.stringify(buildRaceFixture(readFileSync(path, 'utf8')), null, 2)}\n`)
  console.log(`timestamp-race-fixture: rebuilt ${FIXTURE_PATH} from ${path}`)
}
