/** Fragment shader of the real figure material, generated by three's own node
 *  builder for one backend (no GPU needed: code generation only). */
function figureFragmentShader(forceWebGL: boolean): string {
  const g = new THREE.BoxGeometry()
  const n = g.getAttribute('position').count
  for (const name of [SECOND_COLOUR_ATTRIBUTE, SURFACE_ATTRIBUTE])
    g.setAttribute(name, new THREE.Float32BufferAttribute(new Float32Array(n * 4), 4))
  const mesh = new THREE.Mesh(g, figureMaterial(false))
  const renderer = new THREE.WebGPURenderer({ forceWebGL }) as unknown as {
    hasFeature: () => boolean
    lighting: { getNode(s: THREE.Scene): { setLights(l: THREE.Light[]): void } }
    backend: { createNodeBuilder(o: THREE.Object3D, r: unknown): Record<string, unknown> & { build(): void } }
  }
  renderer.hasFeature = () => false // backend not initialised: no optional features
  const scene = new THREE.Scene()
  const light = new THREE.DirectionalLight()
  scene.add(light)
  const lights = renderer.lighting.getNode(scene)
  lights.setLights([light])
  const builder = renderer.backend.createNodeBuilder(mesh, renderer)
  Object.assign(builder, { scene, camera: new THREE.PerspectiveCamera(), lightsNode: lights })
  builder.build()
  return builder.fragmentShader as string
}

/** Then-blocks of every `if` on a figure fibre code (|w - k| < 0.5). */
function fibreBranches(fs: string): string[] {
  const out: string[] = []
  const head = /if \( \( abs\( \( \w+\.w - [1-9]\.0 \) \) < 0\.5 \) \) \{/g
  for (let m = head.exec(fs); m; m = head.exec(fs)) {
    let depth = 1
    let i = m.index + m[0].length
    for (; depth > 0 && i < fs.length; i++) depth += fs[i] === '{' ? 1 : fs[i] === '}' ? -1 : 0
    out.push(fs.slice(m.index + m[0].length, i - 1))
  }
  return out
}

describe('createSurfaceMaterial', () => {
  it('wires a color node AND a baked micro-relief normal node', () => {
    for (const kind of ['plaster', 'mud', 'thatch', 'wood'] as const) {
      const m = createSurfaceMaterial(kind, { base: '#aa8855', alt: '#886633' })
      expect(m.colorNode).toBeTruthy()
      expect(m.normalNode).toBeTruthy()
      expect(m.metalness).toBe(0)
    }
  })

  it('accepts roughness, bump scale and weathering', () => {
    const m = createSurfaceMaterial('mud', {
      base: '#aa8855',
      alt: '#886633',
      bump: 1.3,
      weathered: true,
      roughness: 0.8,
    })
    expect(m.normalNode).toBeTruthy()
    expect(m.roughness).toBe(0.8)
  })
})

describe('loadSurfaceTexture', () => {
  it('sets the distance-stability sampler state: repeat, mips, anisotropy', () => {
    const t = loadSurfaceTexture('plaster_a')
    expect(t.wrapS).toBe(THREE.RepeatWrapping)
    expect(t.wrapT).toBe(THREE.RepeatWrapping)
    expect(t.generateMipmaps).toBe(true)
    expect(t.anisotropy).toBeGreaterThan(1)
    expect(t.colorSpace).toBe(THREE.NoColorSpace)
  })

  it('caches by name (one texture per map)', () => {
    expect(loadSurfaceTexture('ground_n')).toBe(loadSurfaceTexture('ground_n'))
  })

  it('the figure kinds (cloth, leather, skin) get the same sampler state', () => {
    for (const kind of ['cloth', 'leather', 'skin'] as const) {
      for (const map of ['a', 'n'] as const) {
        const t = loadSurfaceTexture(`${kind}_${map}`)
        expect(t.wrapS).toBe(THREE.RepeatWrapping)
        expect(t.wrapT).toBe(THREE.RepeatWrapping)
        expect(t.generateMipmaps).toBe(true)
        expect(t.anisotropy).toBeGreaterThan(1)
        expect(t.colorSpace).toBe(THREE.NoColorSpace)
        expect(loadSurfaceTexture(`${kind}_${map}`)).toBe(t)
      }
    }
  })
})

describe('figure micro-structure (bind-pose triplanar)', () => {
  it('builds a colour factor and a relief normal for the figure kinds', () => {
    const fibre = attribute<'vec4'>('figureColour2', 'vec4').w
    const m = new THREE.MeshStandardNodeMaterial()
    m.colorNode = vec3(0.5, 0.4, 0.3).mul(figureMicroColor(fibre))
    m.normalNode = figureMicroNormal(fibre)
    expect(m.colorNode).toBeTruthy()
    expect(m.normalNode).toBeTruthy()
  })

  // Review finding (perf): every fragment once sampled all three kinds × three
  // planes × two scales for albedo AND normal (36 samples), and fibre `none`
  // still paid them. Pinned on the GENERATED shader of both backends: each
  // kind's maps sit in their own fibre branch (6 samples of one map there),
  // with explicit gradients and no derivative inside the branch, so one
  // fragment pays 12 at most and `none` pays 0.
  for (const [backend, forceWebGL] of [['WGSL', false], ['GLSL', true]] as const) {
    it(`samples only the fragment's own kind (${backend})`, () => {
      const fs = figureFragmentShader(forceWebGL)
      const sample = forceWebGL ? /textureGrad\( (\w+),/g : /textureSampleGrad\( (\w+),/g
      const branches = fibreBranches(fs)
      expect(branches).toHaveLength(6) // 3 kinds × (albedo, normal)
      const figureMaps = new Set<string>()
      for (const body of branches) {
        const maps = [...body.matchAll(sample)].map((m) => m[1])
        expect(maps).toHaveLength(3 * 2) // planes × scales
        expect(new Set(maps).size).toBe(1)
        figureMaps.add(maps[0])
        expect(body).not.toMatch(/dpdx|dpdy|dFdx|dFdy/)
        expect(body).not.toMatch(forceWebGL ? /\btexture\(/ : /textureSample\(/)
      }
      expect(figureMaps.size).toBe(6)
      // No figure map is sampled outside its branch.
      let rest = fs
      for (const body of branches) rest = rest.replace(body, '')
      for (const map of figureMaps) expect(rest).not.toMatch(new RegExp(`\\( ${map}\\b`))
      // Worst case per fragment: one colour branch + one normal branch.
      const perFragment = Math.max(...branches.map((b) => [...b.matchAll(sample)].length)) * 2
      expect(perFragment).toBe(12)
    })
  }

  it('distinct, integer kind codes, none = 0', () => {
    expect(FIGURE_FIBRE.none).toBe(0)
    const codes = Object.values(FIGURE_FIBRE)
    expect(new Set(codes).size).toBe(codes.length)
    for (const c of codes) expect(Number.isInteger(c)).toBe(true)
  })

  it('every figure kind has a positive tile, bump and albedo amount', () => {
    for (const kind of ['cloth', 'leather', 'skin'] as const) {
      expect(FIGURE_MICRO.tile[kind]).toBeGreaterThan(0)
      expect(FIGURE_MICRO.bump[kind]).toBeGreaterThan(0)
      expect(FIGURE_MICRO.albedo[kind]).toBeGreaterThan(0)
      expect(FIGURE_MICRO.albedo[kind]).toBeLessThanOrEqual(1)
    }
  })
})

